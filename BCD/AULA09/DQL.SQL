--EX 6: USO DE AND, OR E NOT
-- AND - TODAS AS CONDIÇÕES PRECISAM SER VERDADEIRAS -
SELECT nome, preco
FROM produto
WHERE preco >= 8.00 AND preco <= 20.00

-- OR - PELO MENOS UMA CONDIÇÃO VERDADEIRA
SELECT NOME, CIDADE
FROM cliente
WHERE cidade = 'Limeira' OR cidade = 'Piracicaba'

-- NOT - NÃO TRAZER O RESULTADO QUE FOI APRESENTADO
SELECT NOME, CIDADE
FROM cliente
WHERE NOT cidade = 'Limeira'

-- JUNTOS - AND E OR
SELECT NOME, CIDADE, ATIVO AS STATUS
FROM cliente
WHERE ativo = TRUE
AND (cidade = 'Limeira' OR CIDADE = 'Americana')

-- EX 7: PEQUISANDO POR INTERVALOS - BETWEEN
