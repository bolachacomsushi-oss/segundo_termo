-- TCL TRANSAÇÕES E INTEGRIDADE REFERENCIAL
-- TRANSAÇÃO RESOLVE PROBLEMAS DE PROCEDIMENTOS, MAS NÃO RESOLVE PROBLEMAS
-- DE INTEGRIDADE REFERENCIAL
-- SEM TRANSAÇÃO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSAÇÃO: PODE CONFIRMAR TUDO OU DESFAZER TUDO
 
-- CONCEITOS INICIAIS
-- TRANSAÇÃO É UM CONJUNTO DE OPERAÇÕES
-- START TRANSACTION
-- INSERT ...
-- UPDATE ...
-- INSERT ...
-- SELECT ...
-- COMMIT;

-- SEQUENCIA
-- INICIO - OPERAÇÕES - VALIDAÇÃO - COMMIT - ROLLBACK

-- EX 1: CONFIRMA AS ALTERAÇÕES DENTRO DA TRANSAÇÃO
START TRANSACTION;
UPDATE produto
SET PRECO = 9.50
WHERE id_produto = 1;
COMMIT

-- EX 2: ROLLBACK - DESFAZ AS ALTERAÇÕES AINDA NÃO CONFIRMDAS
START TRANSACTION;
UPDATE produto
SET preco = 5000.00
WHERE id_produto = 2;
ROLLBACK;


-- EX 3: SAVEPOINT - CRIAR UM PONTO PARA REGISTRAR UMA ETAPA DA TRANSAÇÃO
START TRANSACTION;
UPDATE PRODUTO
SET PRECO = PRECO * 1.05
WHERE id_categoria = 1;
SAVEPOINT REAJUSTE_CAFES;
UPDATE produto
SET PRECO = PRECO * 1.50
WHERE id_categoria = 1;
ROLLBACK TO SAVEPOINT REAJUSTE_CAFES;
COMMIT;

-- EX 4: REMOVE O SAVEPOINT]
RELEASE SAVEPOINT REAJUSTE_CAFES

-- TRANSAÇÃO NÃO SUBSTITUI CONSTRAINT
-- TRANSAÇÃO: CONTROLA SE UM CONJUNTO DE OPERAÇÕES SERÁ CONFIRMADO OU
-- DESFEITO
-- CONSTRAINT: IMPEDE QUE DETERMINADOS ESTADOS INVÁLIDOS SEJAM ACEITOS

-- EX 5: ATUALIZAR ESTOQUE COM VALORES NEGATIVOS
CONSTRAINT CK_ESTOQUE_QUANTIDADE
CHECK (QUANTIDADE >= 0);

--EX 6: INTEGRIDADE REFERENCIAL
CONSTRAINT FK_PEDIDO_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE)
