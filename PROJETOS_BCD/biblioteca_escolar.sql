CREATE DATABASE IF NOT EXISTS BIBLIOTECA_ESCOLAR;
USE BIBLIOTECA_ESCOLAR;
DROP DATABASE BIBLIOTECA_ESCOLAR;

CREATE TABLE ALUNO (
    ID_ALUNO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_ALUNO VARCHAR(100) NOT NULL,
    EMAIL_ALUNO VARCHAR(80) NOT NULL UNIQUE
)

CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT
    TITULO VARCHAR(100) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    AUTOR VARCHAR(120) NOT NULL,
    EDITORA VARCHAR(100)
)

CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT "ABERTO",
    CONSTRAINT FK_EMPRESTIMO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_EMPRESTIMO_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO(ID_LIVRO)
)

